from enum import Enum


class DisputeStatus(str, Enum):
    OPEN = "OPEN"
    UNDER_REVIEW = "UNDER_REVIEW"
    RESOLVED = "RESOLVED"
    REJECTED = "REJECTED"
    CLOSED = "CLOSED"


class DisputeReason(str, Enum):
    PRODUCT_NOT_DELIVERED = "PRODUCT_NOT_DELIVERED"
    INCORRECT_QUANTITY = "INCORRECT_QUANTITY"
    DAMAGED_PRODUCE = "DAMAGED_PRODUCE"
    QUALITY_DISAGREEMENT = "QUALITY_DISAGREEMENT"
    PAYMENT_PROBLEM = "PAYMENT_PROBLEM"
    OTHER = "OTHER"


class DisputeDecision(str, Enum):
    REFUND_BUYER = "REFUND_BUYER"
    RELEASE_TO_SELLER = "RELEASE_TO_SELLER"
    NO_FINANCIAL_ACTION = "NO_FINANCIAL_ACTION"
